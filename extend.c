#include <stdio.h>
#include <stdlib.h>
#include "expopt.h"
/*==========================================================================*/
/*                                                                          */
/*==========================================================================*/
void extend(int l, int add, FILE *f) {
   double *from;
   double *to;
   double   x,z;
   int      n_from,n_to;
   int      k_from,k_to;
   fprintf(f,"Entering extend\n");
/*--------------------------------------------------------------------------*/
/*                                                                          */
/*--------------------------------------------------------------------------*/
   n_from=SYS.basis[l].n;
   n_to=n_from+add;
/*--------------------------------------------------------------------------*/
/* Allocate.                                                                */
/*--------------------------------------------------------------------------*/
   from=SYS.basis[l].z;
   to=(double *)malloc(n_to*sizeof(double));
   SYS.basis[l].z=to;
/*--------------------------------------------------------------------------*/
/* Interpolate.                                                             */
/*--------------------------------------------------------------------------*/
   to[0]=from[0];
   to[n_to-1]=from[n_from-1];
   for(k_to=1; k_to<n_to-1; k_to++) {
      x=(double)(n_from-1)*(double)(k_to)/(double)(n_to-1);
      k_from=(int)(x);
      x=x-(double)(k_from);
      z=(1.0-x)*from[k_from]+x*from[k_from+1];
      to[k_to]=z;
   }
   fprintf(f,"From exponents\n");
   for(k_from=0; k_from<n_from; k_from++) {
      if( (k_from!=0) && (k_from%5==0) ) fprintf(f,"\n");
      fprintf(f,"%12.6f ",from[k_from]);
   }
   fprintf(f,"\n");
   fprintf(f,"To exponents\n");
   for(k_to=0; k_to<n_to; k_to++) {
      if( (k_to!=0) && (k_to%5==0) ) fprintf(f,"\n");
      fprintf(f,"%12.6f ",to[k_to]);
   }
   fprintf(f,"\n");
/*--------------------------------------------------------------------------*/
/* Dealocate.                                                               */
/*--------------------------------------------------------------------------*/
   SYS.basis[l].n=n_to;
   free(from);
/*--------------------------------------------------------------------------*/
/*                                                                          */
/*--------------------------------------------------------------------------*/
   fprintf(f,"Exiting extend\n");
}
