void sort_xy(double x[], double y[], int n) {
   double t;
   int i,j,k;
   for (i=0; i<n; i++) {
      k=i;
      for (j=i; j<n; j++) if (x[j]<x[k]) k=j;
      t=x[i]; x[i]=x[k]; x[k]=t;
      t=y[i]; y[i]=y[k]; y[k]=t;
   }
}
