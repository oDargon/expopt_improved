double check_lin_dep(double M[MAX_DIR][MAX_DIR], int n, FILE *f) {
   double S[MAX_DIR*(MAX_DIR+1)/2];
   double U[MAX_DIR*MAX_DIR];
   double t;
   int    ind;
   int    i,j,k;
   fprintf(f,"Entering check_lin_dep\n");
/*--------------------------------------------------------------------------*/
/* Initialize.                                                              */
/*--------------------------------------------------------------------------*/
/*--------------------------------------------------------------------------*/
/* Form overlap matrix                                                      */
/*--------------------------------------------------------------------------*/
   ind=0;
   for(i=0; i<n; i++) {
      for(j=0; j<i+1; j++) {
         S[ind]=0.0;
         for(k=0; k<n; k++) S[ind]=S[ind]+M[i][k]*M[j][k];
         ind++;
      }
   }
   ind=0;
   for(i=0; i<n; i++) {
      for(j=0; j<i+1; j++) { fprintf(f," %12.6f",S[ind]); ind++; } fprintf(f,"\n");
   }
   fprintf(f,"\n");
/*--------------------------------------------------------------------------*/
/* Diagonalize overlap matrix                                               */
/*--------------------------------------------------------------------------*/
   for(i=0; i<n; i++) {
      for(j=0; j<n; j++) U[i+n*j]=0.0;
      U[i+n*i]=1.0;
   }
   jacobi(S,U,n,n);
   ind=0;
   for(i=0; i<n; i++) {
      for(j=0; j<i+1; j++) { fprintf(f," %12.6f",S[ind]); ind++; } fprintf(f,"\n");
   }
   fprintf(f,"\n");
   for(i=0; i<n; i++) {fprintf(f," %12.6f",S[i*(i+3)/2]);} fprintf(f,"\n");
   for(i=0; i<n; i++) {
      for(j=0; j<n; j++) {fprintf(f," %12.6f",U[i+n*j]);} fprintf(f,"\n");
   }
/*--------------------------------------------------------------------------*/
/* Find smallest eigenvalue.                                                */
/*--------------------------------------------------------------------------*/
   k=0;
   for(i=0; i<n; i++) if(S[i*(i+3)/2]<S[k*(k+3)/2]) k=i;
   t=S[k*(k+3)/2];
/*--------------------------------------------------------------------------*/
/* Transfer directions to caller.                                           */
/*--------------------------------------------------------------------------*/
   for(i=0; i<n; i++) {
      for(j=0; j<n; j++) M[i][j]=U[i+n*j];
   }
/*--------------------------------------------------------------------------*/
/*                                                                          */
/*--------------------------------------------------------------------------*/
   return t;
   fprintf(f,"Exiting check_lin_dep\n");
}
