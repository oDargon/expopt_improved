#include <stdio.h>
#include <stdlib.h>
#include <math.h>
#include "expopt.h"
#define MAX_ITER 50
typedef struct {
   double   energy;
   double  *x;
   double  *g;
   double  *h;
} point;
/*==========================================================================*/
/*                                                                          */
/*==========================================================================*/
void qn2(double x[], int n, double ethr, double gthr, FILE *f) {
   point   P[MAX_ITER+1];
   double *B;
   double *t;
   double  e0,ep,em;
   double  d;
   int     i;
   fprintf(f,"Entering qn2\n");
/*--------------------------------------------------------------------------*/
/*                                                                          */
/*--------------------------------------------------------------------------*/
/*--------------------------------------------------------------------------*/
/* Allocate.                                                                */
/*--------------------------------------------------------------------------*/
/* ... allocate P.x, etc */
   B=(double *)malloc(n*n*sizeof(double));
   t=(double *)malloc(n*sizeof(double));
/*--------------------------------------------------------------------------*/
/* Initialize.                                                              */
/*--------------------------------------------------------------------------*/
   for(i=0; i<n; i++) P[0].x[i]=x[i]; /* initial point */
   for(i=0; i<n; i++) t[i]=P[0].x[i]; /* temporary point */
   e0=energy(t);
   d=0.01;
   for(i=0; i<n; i++) {               /* scale directions to get unit hessian */
      t[i]=t[i]+1.0*d; ep=energy(t);
      t[i]=t[i]-2.0*d; em=energy(t);
      t[i]=t[i]+1.0*d;
      printf("e0=%.6f\n",e0);
      printf("ep=%.6f\n",ep);
      printf("em=%.6f\n",em);
   }
/*--------------------------------------------------------------------------*/
/* Iterate.                                                                 */
/*--------------------------------------------------------------------------*/
/*--------------------------------------------------------------------------*/
/* Deallocate vertices.                                                     */
/*--------------------------------------------------------------------------*/
   free(t);
   free(B);
/*--------------------------------------------------------------------------*/
/*                                                                          */
/*--------------------------------------------------------------------------*/
   fprintf(f,"Exiting qn2\n");
   fprintf(stderr,"qn2 not yet implemented, exiting!\n");
   exit(1);
}
