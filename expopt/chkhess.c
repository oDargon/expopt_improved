#include <stdio.h>
#include <stdlib.h>
#include <math.h>
#include "expopt.h"
/*--------------------------------------------------------------------------*/
#define tri(i,j) ((i*(i+1))/2+j)
#define sqr(i,j) (i+n*j)
/*==========================================================================*/
/*                                                                          */
/*==========================================================================*/
void check_hessian(double B[], int n) {
   double *H;
   double *U;
   double  hBig,hSmall,thr;
   double  t,d;
   int     i,j,k;
   printf("Entering check_hessian\n");
/*--------------------------------------------------------------------------*/
/* Allocate and clear.                                                      */
/*--------------------------------------------------------------------------*/
   H=(double *)malloc((n*(n+1))/2*sizeof(double));
   U=(double *)malloc(n*n*sizeof(double));
   for(i=0; i<n; i++) {
      for(j=0; j<n; j++) U[sqr(i,j)]=0.0;
      U[sqr(i,i)]=1.0;
   }
   for(i=0; i<n; i++) {
      for(j=0; j<=i; j++) H[tri(i,j)]=B[sqr(i,j)];
   }
/*--------------------------------------------------------------------------*/
/* Compute threshold.                                                       */
/*--------------------------------------------------------------------------*/
   hBig=fabs(H[0]);
   hSmall=fabs(H[0]);
   for(i=0; i<n; i++) {
      t=fabs(H[tri(i,i)]);
      if(hBig<t)   hBig=t;
      if(hSmall>t) hSmall=t;
   }
   thr=0.10e0*hSmall;
   if(thr<1.0e-4*hBig) thr=1.0e-4*hBig;
   printf("hSmall %10.6f\n",hSmall);
   printf("hBig   %10.6f\n",hBig);
   printf("thr    %10.6f\n",thr);
/*--------------------------------------------------------------------------*/
/* Diagonalize hessian.                                                     */
/*--------------------------------------------------------------------------*/
   jacobi(H,U,n,n);
   printf("Eigenvalues:\n");
   for(i=0; i<n; i++) {
      if( (i!=0) && (i%5==0) ) printf("\n");
      printf("%12.6f ",H[tri(i,i)]);
   }
   printf("\n");
/*--------------------------------------------------------------------------*/
/* Reasseble hessian.                                                       */
/*--------------------------------------------------------------------------*/
   for(i=0; i<n; i++) {
      for(j=0; j<n; j++) {
         t=0.0;
         for(k=0; k<n; k++) {
            d=H[tri(k,k)];
            if(d<thr) d=thr;
            t=t+d*U[sqr(i,k)]*U[sqr(j,k)];
         }
         B[sqr(i,j)]=t;
      }
   }
   printf("Reassembled hessian\n");
   for(i=0; i<n; i++) {
      for(j=0; j<n; j++) printf("%12.6f ",B[sqr(i,j)]);
      printf("\n");
   }
/*--------------------------------------------------------------------------*/
/* Deallocate.                                                              */
/*--------------------------------------------------------------------------*/
   free(H);
   free(U);
/*--------------------------------------------------------------------------*/
/*                                                                          */
/*--------------------------------------------------------------------------*/
   printf("Exiting check_hessian\n");
}
