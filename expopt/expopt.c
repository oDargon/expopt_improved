#include <stdio.h>
#include "expopt.h"
sysdef    SYS;
/*==========================================================================*/
/*                                                                          */
/*==========================================================================*/
int main(int argc, char *argv[]) {
   int i;
/*--------------------------------------------------------------------------*/
/*                                                                          */
/*--------------------------------------------------------------------------*/
   SYS.charge    = 0.0;
   SYS.ethr      = 1.0e-6;
   SYS.gthr      = 1.0e-3;
   SYS.pen_a     = 0.0;
   SYS.pen_b     = 0.2;
   SYS.pen_c     = 20.0;
   SYS.B0        = 0.005;
   SYS.A0        = 0.01;
   SYS.alpha     = 0.50;
   SYS.fnc_eval  = 0;
   SYS.verbose   = 0;
   SYS.method    = OPT_AMOEBA;
   SYS.method    = OPT_QN;
   SYS.generator = GEN_POLY;
   SYS.active    = -1;
   SYS.n_dir     = 0;
   SYS.index     = NULL;
   SYS.printthis       = -1;
   SYS.printraw        = 0;
   SYS.contract_frozen = 0;
   SYS.no_linesearch   = 0;
   for(i=0; i<=MAX_LQN; i++) {
      SYS.basis[i].Z=0;
      SYS.basis[i].l=0;
      SYS.basis[i].n=0;
      SYS.basis[i].m=0;
      SYS.basis[i].z=NULL;
      SYS.basis[i].c=NULL;
   }
/*--------------------------------------------------------------------------*/
/*                                                                          */
/*--------------------------------------------------------------------------*/
   printf("***\n");
   printf("*** ExpOpt version %s\n",VERSION);
   printf("***\n");
/*--------------------------------------------------------------------------*/
/*                                                                          */
/*--------------------------------------------------------------------------*/
   input_control(stdin,stdout);
   printf("\nFunction evaluations: %i\n",SYS.fnc_eval);
/*--------------------------------------------------------------------------*/
/*                                                                          */
/*--------------------------------------------------------------------------*/
   return 0;
}
