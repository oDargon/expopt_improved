/****************************************************************************/
/*                                                                          */
/****************************************************************************/
#include <stdio.h>
#include <stdlib.h>
#include <math.h>
#include "expopt.h"
#define MAX_ITER 256
#define GS         1.61803398875
/*==========================================================================*/
/*                                                                          */
/*==========================================================================*/
double line_search(double *z, double *s, int n, double *s0, double ethr, FILE *f) {
   double  x[MAX_ITER];
   double  e[MAX_ITER];
   double *t;
   double  p,q;
   double  xm,em,d2;
   double  thr;
   int     i,k,m;
   fprintf(f,"Entering line_search\n");
/*--------------------------------------------------------------------------*/
/* Init                                                                     */
/*--------------------------------------------------------------------------*/
   t=(double *)malloc(n*sizeof(double));
/*--------------------------------------------------------------------------*/
/* Prime line search.                                                       */
/*--------------------------------------------------------------------------*/
   x[0]=0.0; x[1]=*s0;
   for(k=0; k<2; k++) {
      for(i=0; i<n; i++) t[i]=z[i]+x[k]*s[i]; e[k]=energy(t);
   }
   if(e[0]<e[1]) {
      x[2]=x[1]; x[1]=x[0]; x[0]=x[2];
      e[2]=e[1]; e[1]=e[0]; e[0]=e[2];
   }
   for(k=0; k<2; k++) fprintf(f,"x[%2i]=%15.8f, e[%2i]=%15.8f\n",k,x[k],k,e[k]);
/*--------------------------------------------------------------------------*/
/* Bracket minimum.                                                         */
/*--------------------------------------------------------------------------*/
   k=2;
   while(k<20) {
      x[k]=(1.0+GS)*x[k-1]-GS*x[k-2];
      for(i=0; i<n; i++) t[i]=z[i]+x[k]*s[i]; e[k]=energy(t);
      fprintf(f,"x[%2i]=%15.8f, e[%2i]=%15.8f\n",k,x[k],k,e[k]);
      if(e[k]>e[k-1]) break;
      k++;
   }
   m=k-1;
   k=k+1;
   thr=0.3*fabs(e[0]-e[m]);
   fprintf(f,"ethr=%.6e, thr=%.6e\n",ethr,thr);
   if(thr<ethr) thr=ethr;
   if(n==1)     thr=ethr;
   thr=ethr;  /* quick fix */
/*--------------------------------------------------------------------------*/
/* Refine minimum.                                                          */
/*--------------------------------------------------------------------------*/
   while( (d2=fabs(e[m-1]-e[m])+fabs(e[m]-e[m+1])) > thr) {
      if(0) {
         p=  e[m-1]*(x[m+1]*x[m+1]-x[m  ]*x[m  ])
            -e[m  ]*(x[m+1]*x[m+1]-x[m-1]*x[m-1])
            +e[m+1]*(x[m  ]*x[m  ]-x[m-1]*x[m-1]);
         q=  e[m-1]*(x[m+1]-x[m  ])
            -e[m  ]*(x[m+1]-x[m-1])
            +e[m+1]*(x[m  ]-x[m-1]);
         xm=0.5*p/q;
         for(i=0; i<n; i++) t[i]=z[i]+xm*s[i]; em=energy(t);
         fprintf(f,"xm=%15.8f, em=%15.8f\n",xm,em);
      }
      if(fabs(x[m+1]-x[m])<fabs(x[m]-x[m-1])) {
         x[k]=(GS*x[m]+x[m-1])/(GS+1.0);
         for(i=0; i<n; i++) t[i]=z[i]+x[k]*s[i]; e[k]=energy(t);
         if(e[k]<e[m]) {
            x[m+1]=x[m]; x[m]=x[k];
            e[m+1]=e[m]; e[m]=e[k];
         } else {
            x[m-1]=x[k];
            e[m-1]=e[k];
         }
      } else {
         x[k]=(GS*x[m]+x[m+1])/(GS+1.0);
         for(i=0; i<n; i++) t[i]=z[i]+x[k]*s[i]; e[k]=energy(t);
         if(e[k]<e[m]) {
            x[m-1]=x[m]; x[m]=x[k];
            e[m-1]=e[m]; e[m]=e[k];
         } else {
            x[m+1]=x[k];
            e[m+1]=e[k];
         }
      }
      fprintf(f,"d2=%.8f\n",d2);
      for(i=m-1; i<m+2; i++) fprintf(f,"x[%2i]=%15.8f, e[%2i]=%15.8f\n",i,x[i],i,e[i]);
   }
   fprintf(f,"d2=%.8f\n",d2);
/*--------------------------------------------------------------------------*/
/* Parabolic fit                                                            */
/*--------------------------------------------------------------------------*/
   p=  e[m-1]*(x[m+1]*x[m+1]-x[m  ]*x[m  ])
      -e[m  ]*(x[m+1]*x[m+1]-x[m-1]*x[m-1])
      +e[m+1]*(x[m  ]*x[m  ]-x[m-1]*x[m-1]);
   q=  e[m-1]*(x[m+1]-x[m  ])
      -e[m  ]*(x[m+1]-x[m-1])
      +e[m+1]*(x[m  ]-x[m-1]);
   xm=0.5*p/q;
   for(i=0; i<n; i++) t[i]=z[i]+xm*s[i]; em=energy(t);
   fprintf(f,"xm=%16.10f, em=%16.10f\n",xm,em);
/*--------------------------------------------------------------------------*/
/* Transfer minimum                                                         */
/*--------------------------------------------------------------------------*/
   for(i=0; i<n; i++) z[i]=z[i]+xm*s[i];
   *s0=xm;
/*--------------------------------------------------------------------------*/
/*                                                                          */
/*--------------------------------------------------------------------------*/
   free(t);
/*--------------------------------------------------------------------------*/
/*                                                                          */
/*--------------------------------------------------------------------------*/
   fprintf(f,"Exiting line_search\n");
   return em;
}
