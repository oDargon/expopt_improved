/**************************************************************************/
/*                                                                        */
/*                               G A U S S                                */
/*                                                                        */
/*========================================================================*/
/*                                                                        */
/* This subroutine performs gauss elimination on the matrix a. The        */
/* system of equations solved is ax=c.                                    */
/* No pivoting is performed.                                              */
/*                                                                        */
/*========================================================================*/
/*                                                                        */
/* Author:  Per-Olof Widmark                                              */
/* Written: May 1993                                                      */
/* History:                                                               */
/*                                                                        */
/*========================================================================*/
/*                                                                        */
/*                                                                        */
/**************************************************************************/
void gauss(double a[], double x[], double c[], int n) {
   int i,j,k,kn;
   double aiir;
   double f,t;
   for (i=0; i<n; i++) x[i]=c[i];
/*------------------------------------------------------------------------*/
/* Forwards elimination                                                   */
/*------------------------------------------------------------------------*/
   for (i=0; i<n-1; i++) {
      aiir=1/a[i+i*n];
      for (j=i+1; j<n; j++) {
         f=a[j+i*n]*aiir;
         kn=i*n;
         for (k=i+1; k<n; k++) {
           kn=kn+n;
           a[j+kn]=a[j+kn]-f*a[i+kn];
         }
         x[j]=x[j]-f*x[i];
      }
   };
/*------------------------------------------------------------------------*/
/* Backwards elimination                                                  */
/*------------------------------------------------------------------------*/
   x[n-1]=x[n-1]/a[(n-1)*(n+1)];
   for (i=n-2; i>-1; i--) {
      t=x[i];
      for (k=i+1; k<n; k++) t=t-x[k]*a[i+k*n];
      x[i]=t/a[i+i*n];
   }
/*------------------------------------------------------------------------*/
/*                                                                        */
/*------------------------------------------------------------------------*/
}
